# -*- coding: utf-8 -*-
"""Generate assets/data/places.js, tours.js and l10n/<lang>.js from build/tours_data.py and build/l10n/*.py"""
import json, os, importlib, sys
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import tours_data as D

LANGS = ["en", "ru", "uz", "tr", "ar", "de", "sv", "zh", "hi", "ko"]

def js(name, obj):
    return "/* generated by build/build_tours.py — do not edit */\nwindow.%s = %s;\n" % (name, json.dumps(obj, ensure_ascii=False, separators=(",", ":")))

def places():
    cities = {c: {"country": v[0], "lat": v[1], "lon": v[2], "img": v[3], **({"hidden": True} if v[4] else {})} for c, v in D.CITIES.items() if c in D.USED_CITIES}
    legs = [{"a": a, "b": b, "km": km, "h": h, "mode": m, "note": n} for a, b, km, h, m, n in D.LEGS]
    return {"cities": cities, "legs": legs}

def tours():
    out = {}
    for t in D.TOURS:
        days = []
        for sleep, moves, stops, meals in t["days"]:
            d = {"sleep": sleep, "meals": meals, "stops": [{"id": s, "img": D.SIGHTS[s][1], "city": D.SIGHTS[s][0]} for s in stops]}
            if moves: d["move"] = moves
            days.append(d)
        hl = []
        for d in t["days"]:
            if d[2] and d[2][0] not in hl: hl.append(d[2][0])
        out[t["id"]] = {"id": t["id"], "country": t["country"], "cover": t["cover"], "hotel": t["hotel"], "flags": t["flags"], "season": t["season"],
                        "days": days, "hl": hl[1:5] if len(hl) > 4 else hl, "inc": t["inc"], "exc": t["exc"], "bring": t["bring"]}
    return out

BRING_ICON = {"passport": "passport", "shoes": "shoes", "scarf": "scarf", "sun": "sun", "jacket": "jacket", "cash": "cash", "plug": "plug",
              "meds": "meds", "boots": "shoes", "warm": "jacket", "bag": "passport"}

def l10n(lang):
    m = importlib.import_module("l10n." + lang)
    en = importlib.import_module("l10n.en")
    def pick(attr, keys):
        src, base = getattr(m, attr), getattr(en, attr)
        missing = [k for k in keys if k not in src]
        if missing: print("  [%s] %s missing %d: %s" % (lang, attr, len(missing), missing[:6]))
        return {k: src.get(k, base[k]) for k in keys}
    return {"lang": lang,
            "ui": {**en.UI, **m.UI},
            "items": pick("ITEMS", list(en.ITEMS)), "legnotes": pick("LEGNOTES", list(en.LEGNOTES)),
            "hotels": pick("HOTELS", list(en.HOTELS)), "transport": pick("TRANSPORT", list(en.TRANSPORT)), "guide": pick("GUIDE", list(en.GUIDE)),
            "cities": pick("CITIES", D.USED_CITIES), "sights": pick("SIGHTS", D.USED_SIGHTS), "tours": pick("TOURS", [t["id"] for t in D.TOURS]),
            "bringIcon": BRING_ICON}

def main():
    d = os.path.join(ROOT, "assets", "data"); os.makedirs(os.path.join(d, "l10n"), exist_ok=True)
    open(os.path.join(d, "places.js"), "w").write(js("MN_PLACES", places()))
    open(os.path.join(d, "tours.js"), "w").write(js("MN_TOURS", tours()))
    for lang in LANGS:
        if os.path.exists(os.path.join(HERE, "l10n", lang + ".py")):
            open(os.path.join(d, "l10n", lang + ".js"), "w").write(js("MN_L", l10n(lang)))
            print("ok l10n/" + lang + ".js")
    print("tours:", len(D.TOURS), "sights:", len(D.USED_SIGHTS), "cities:", len(D.USED_CITIES))

if __name__ == "__main__":
    main()
